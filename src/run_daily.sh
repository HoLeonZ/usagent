#!/usr/bin/env bash
# usagent 每日数据任务 —— **只采集标的数据**（不碰交易；下单仍是人工）。
#
# 2026-10-17：**主体已搬进 `src/daily.py`**，本脚本只剩一层壳。为什么（机构就绪审计）：
#   * 池子/源/增量天数此前写死在这里（`--universe oi100`，596 只），而引擎与面板读的是
#     **全库 3028 只** ⇒ 每日任务不覆盖真正的机会集，且"数据新鲜"判的是全库 MAX(date)
#     （由永远在更新的那 596 只决定）⇒ **判据看不见这件事**；
#   * 失败只 echo 到 stdout、`logs/` 是空目录 ⇒ "跑完了"与"跑失败了"事后无法区分；
#   * shell 字符串里的逻辑没法测。现在"今天的计划"是数据（`daily.plan()`），可打印、可单测。
# 不变的：解释器不写死（`PY=...` 可覆盖）、cron 接口不变、任一阶段失败即非零退出。
#
# 保留的历史（它解释了为什么这条链"运行时刻无约束"）：
#   2026-10-14 本脚本曾含「期权链快照」与「IV 反解」两步，已移除 —— 只需要标的数据做分析、
#   手动下单，不需要期权链。三条连带好处：① 不再受"Yahoo 深夜清零期权报价"的时段约束；
#   ② cron 的星期字段不再是"每周丢一天"；③ 单轮耗时从 ~110 分钟降到 ~7 分钟。
#   若将来要重采期权链：把 `config.COLLECT_OPTIONS` 置 True，并在 `daily.plan()` 里加回两步
#   （届时时段约束会重新生效）。
#
# 用法：
#   bash src/run_daily.sh                  # 跑今天的任务
#   bash src/run_daily.sh --dry-run        # 只打印今天的计划（池子/源/命令行）
#   bash src/run_daily.sh --quiet          # 成功步骤不刷屏（失败仍然打印）
#   crontab（机器时区需为北京）:
#       0 10 * * 1-5  cd <仓库根> && bash src/run_daily.sh >> logs/daily.log 2>&1

set -uo pipefail
cd "$(dirname "$0")/.." || exit 1
# 解释器**不写死某一台机器的路径**（审计 G2）：可用 PY=... 覆盖。
PY="${PY:-python3}"
mkdir -p logs
exec "$PY" -u src/daily.py "$@"
